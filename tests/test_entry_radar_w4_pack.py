def ripple(i: int, amp: float = 0.04, period: float = 11.0) -> float:
    return 1.0 + amp * math.sin(2.0 * math.pi * i / period)


def sessions_ending(n: int, end: date = AS_OF) -> pd.DatetimeIndex:
    reference = session_anchor.reference_sessions("US")
    position = int(reference.searchsorted(pd.Timestamp(end).normalize(), side="right"))
    return pd.DatetimeIndex(reference[max(0, position - n):position])


def frame_from_closes(closes, end: date = AS_OF) -> pd.DataFrame:
    index = sessions_ending(len(closes), end)
    values = np.asarray(list(closes)[-len(index):], dtype=float)
    return pd.DataFrame({"open": values, "high": values * 1.01,
                         "low": values * 0.99, "close": values,
                         "volume": np.full(len(values), 1_000.0)},
                        index=index)


def washout_closes() -> list[float]:
    """A long rippled decline, then a steady slide — %K pinned at 0.

    Its prior two ``rawk`` values sit at the 14-bar minimum, which is what leaves
    room for ``K = SMA(3)`` to cross 20 as the appended close moves: the C1 level
    EXISTS for this shape.
    """
    prefix = [(200.0 - 0.5 * i) * ripple(i) for i in range(180)]
    return prefix + [prefix[-1] * (0.975 ** k) for k in range(1, 13)]


def vshape_closes() -> list[float]:
    """A deep washout, then two strong up bars — the saturation shapes.

    C1 is ``never_true`` here (at 3x the close ``rawk`` saturates at 100, so
    ``K >= 33`` whatever the price) and C2a is ``always_true`` (``K - D`` is
    positive across the whole bracket).  Both are §7.1's own named degeneracies.
    """
    prefix = [(200.0 - 0.5 * i) * ripple(i) for i in range(180)]
    body = prefix + [prefix[-1] * (0.97 ** k) for k in range(1, 11)]
    return body + [body[-1] * 1.13, body[-1] * 1.30]


FLAT_CLOSES = [100.0] * 200
SHORT_CLOSES = [100.0 + i for i in range(8)]


def store(**overrides) -> dict[str, pd.DataFrame]:
    frames = {
        "WASH": frame_from_closes(washout_closes()),
        "VSHAPE": frame_from_closes(vshape_closes()),
        "FLAT": frame_from_closes(FLAT_CLOSES),
        "SHORT": frame_from_closes(SHORT_CLOSES),
        # last_confirmed lags AS_OF by weeks — the per-name staleness case
        "STALE": frame_from_closes(washout_closes(), date(2026, 7, 10)),
    }
    frames.update(overrides)
    return frames


def reader_for(frames):
    def reader(ticker: str):
        return frames.get(ticker)
    return reader


def build(frames=None, *, tickers=None, built_at=None, **kwargs) -> lp.LivePack:
    frames = store() if frames is None else frames
    return lp.build_pack(
        probe_set=list(tickers if tickers is not None else sorted(frames)),
        store_reader=reader_for(frames), as_of=AS_OF,
        built_at=built_at or datetime(2026, 8, 15, 2, 0, tzinfo=timezone.utc),
        **kwargs)


