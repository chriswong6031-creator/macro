def oracle_for(pack: lp.LivePack, ticker: str) -> lp.OracleFrame:
    frame = pack.substrate[ticker]
    return lp.OracleFrame(
        ticker=ticker, closes=frame["close"].astype(float).to_numpy(dtype=float),
        index=pd.DatetimeIndex(frame.index),
        next_session_ts=pd.Timestamp(pack.next_session).normalize())


