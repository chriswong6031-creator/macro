@pytest.mark.parametrize("condition,margin", [
    ("c1_arm_price", lp._c1_margin),
    ("c2a_cross_price", lp._c2a_margin),
])
def test_PACK3_a_solved_level_agrees_with_the_oracle_on_both_sides(pack, condition,
                                                                   margin):
    row = pack.by_ticker()["WASH"]
    solution = getattr(row, condition)
    assert not solution.no_threshold_exists, f"WASH should solve {condition}"
    frame = oracle_for(pack, "WASH")
    level = float(solution.price)
    for side in (1.0 - lp.PROOF_EPSILON_REL, 1.0 + lp.PROOF_EPSILON_REL):
        price = level * side
        observed = margin(frame, price) > 0.0
        assert observed is solution.holds_at(price), (
            f"{condition} disagrees with the oracle at {price}")


def test_PACK3_the_two_conditions_run_in_OPPOSITE_directions(pack):
    row = pack.by_ticker()["WASH"]
    assert row.c1_arm_price.direction == "below"
    assert row.c2a_cross_price.direction == "above"


def test_PACK3_condition_at_boundary_is_the_oracle_verdict_AT_the_level(pack):
    row = pack.by_ticker()["WASH"]
    frame = oracle_for(pack, "WASH")
    for solution, margin in ((row.c1_arm_price, lp._c1_margin),
                             (row.c2a_cross_price, lp._c2a_margin)):
        if solution.no_threshold_exists:
            continue
        assert solution.condition_at_boundary is (margin(frame, solution.price) > 0.0)
        assert solution.holds_at(solution.price) is solution.condition_at_boundary


def test_PACK3_bisection_meets_the_declared_relative_tolerance(pack):
    row = pack.by_ticker()["WASH"]
    frame = oracle_for(pack, "WASH")
    level = float(row.c1_arm_price.price)
    # Ten tolerances either side must already be decided; the level is not a
    # fuzzy region.
    span = float(row.as_of_close) * lp.BISECTION_REL_TOLERANCE * 10.0
    assert (lp._c1_margin(frame, level - span) > 0.0) is True
    assert (lp._c1_margin(frame, level + span) > 0.0) is False


def test_PACK3_the_oracle_mirrors_build_observation_path_exactly(pack):
    """The level's own construction and the live path's must be one construction.

    If these two diverge the pack becomes a second implementation of the
    oscillator — the exact defect ``indicator_core``'s module docstring exists to
    prevent — and every level in it would be about a series nobody evaluates.
    """
    frame = pack.substrate["WASH"]
    history = ch.DailyHistory(frame=frame, price_basis=ch.BASIS_ADJUSTED,
                              vintage="w4-fixture")
    price = float(pack.by_ticker()["WASH"].as_of_close) * 0.97
    open_dt, _close = ch.session_window_et(NEXT_SESSION)
    tape = ch.SessionTape(
        session=NEXT_SESSION,
        minutes=(ch.MinuteBar(start=open_dt + timedelta(minutes=1), open=price,
                              high=price, low=price, close=price),),
        price_basis=ch.BASIS_ADJUSTED, vintage="w4-fixture")
    observations = ch.build_observation_path(ticker="WASH", daily=history, tapes=[tape])
    live_k = observations[0].k
    oracle_k, _d = oracle_for(pack, "WASH").kd(price)
    assert live_k == pytest.approx(oracle_k, rel=0, abs=0)


