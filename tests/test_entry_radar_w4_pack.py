def test_PACK6a_a_corrupted_level_fails_the_proof_and_NAMES_the_case(pack):
    names = list(pack.names)
    index = next(i for i, n in enumerate(names)
                 if not n.c1_arm_price.no_threshold_exists)
    victim = names[index]
    names[index] = _with_moved_level(victim)
    corrupted = lp.LivePack(
        schema=pack.schema, as_of=pack.as_of, next_session=pack.next_session,
        built_at=pack.built_at, price_basis=pack.price_basis,
        spec_hashes=pack.spec_hashes, probe_set=pack.probe_set, names=tuple(names),
        substrate=pack.substrate, pack_hash=pack.pack_hash)
