    assert result["by_family"]["threshold_boundary"]["failed"] > 0
    named = {case["case"] for case in result["failures"]}
    assert any(case.startswith(f"{victim.ticker}:c1_arm_price") for case in named), named
    assert corrupted.with_proof(result).proof_failed is True


