_BREAKOUT_TITLE = 'Note </script><img src=x onerror=alert(1)><script>'


def test_a_title_cannot_break_out_of_the_jsonld_script_element(tmp_path, capsys):
    """SCRIPT INJECTION THROUGH A HEADLINE.

    HTML parsing beats JSON parsing: `</script>` inside the ld+json block ends
    the element early and everything after it is parsed as MARKUP. The title
    comes from a .md file, and a .md file is written by an LLM — so this is
    reachable by anything that can influence a draft title.
    """
    url = "https://mastermindx.ai/articles/breakout-note.html"
    root = _property_root(tmp_path, [_row("breakout-note", url=url)])
    _write_md(root / "content" / "seo" / "blog" / "breakout-note.md", "breakout-note",
              title=_BREAKOUT_TITLE)
    tree = tmp_path / "out"
    PR.render_property(root, P.load_config(root), "mastermind_news", dest=tree)
    capsys.readouterr()

    page = (tree / "articles" / "breakout-note.html").read_text(encoding="utf-8")
    raw = re.search(r'<script type="application/ld\+json">(.*?)</script>',
                    page, re.DOTALL).group(1)

    assert "</script>" not in raw, "the JSON-LD block can be closed from inside"
    assert "<script>" not in raw and "<img" not in raw
    data = json.loads(raw)
    # The ESCAPE is on the wire only — the parsed object is unchanged.
    assert data["headline"] == _BREAKOUT_TITLE


def test_the_script_escape_leaves_the_parsed_object_identical():
    """`\\u003c` and friends are ordinary JSON escapes, so escaping must be
    invisible to a parser."""
    payload = {"a": "<b>&amp;</b>", "b": "already \\u003c literal",
               "c": "5 > 3 & 2 < 4", "d": "</script>"}
    raw = json.dumps(payload, ensure_ascii=False)
    escaped = PR._script_safe_json(raw)

    assert json.loads(escaped) == payload, "escaping changed the parsed object"
    for ch in "<>":
        assert ch not in escaped, f"{ch!r} survived the escape"
    assert "</script>" not in escaped


def test_the_script_escape_is_order_independent():
    """The obvious worry about three chained .replace() calls is that one pass
    corrupts another's output.  It cannot, and this pins WHY rather than
    freezing an arbitrary order: every replacement emits `\\u00XX`, and none of
    the characters in that output is one of the three triggers `&`, `<`, `>`.
    Disjoint alphabets in and out, so all six orderings agree.

    Written as an equivalence rather than "& must be first" so that a future
    reshuffle of those three lines cannot silently start mattering.
    """
    import itertools

    payload = {"x": "</script> & <b>5 > 3</b> &amp; \\u0026 literal"}
    raw = json.dumps(payload, ensure_ascii=False)
    subs = {"&": "\\u0026", "<": "\\u003c", ">": "\\u003e"}

    results = set()
    for order in itertools.permutations(subs):
        out = raw
        for ch in order:
            out = out.replace(ch, subs[ch])
        results.add(out)
    assert len(results) == 1, (
        f"the three escapes are NOT order-independent ({len(results)} distinct "
        "results) — the disjoint-alphabet argument in _script_safe_json is wrong")
    assert results.pop() == PR._script_safe_json(raw)
    assert json.loads(PR._script_safe_json(raw)) == payload


