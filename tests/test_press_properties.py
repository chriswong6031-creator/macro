_CLOCK_READS = ("datetime.now", "utcnow", ".today(", "time.time", "time.gmtime",
                "time.localtime", "time.monotonic", "st_mtime", "getmtime")

# One probe per token. A sentinel with nine tokens and one probe proves one
# token works and the other eight are decoration.
_CLOCK_PROBES = {
    "datetime.now": "x = datetime.now(timezone.utc)",
    "utcnow": "x = datetime.utcnow()",
    ".today(": "x = date.today()",
    "time.time": "x = time.time()",
    "time.gmtime": "x = time.gmtime()",
    "time.localtime": "x = time.localtime()",
    "time.monotonic": "x = time.monotonic()",
    "st_mtime": "x = path.stat().st_mtime",
    "getmtime": "x = os.path.getmtime(path)",
}


@pytest.mark.parametrize("rel", ["engine/press/properties.py",
                                 "scripts/build_press_properties.py"])
def test_the_property_renderer_reads_no_clock(rel):
    """DETERMINISM IS THE CONTRACT.  One wall-clock read — a "generated at"
    stamp, an RSS lastBuildDate taken from the current instant — makes
    `build_press_properties --check` red on every single run, and a check that
    is always red is a check that gets deleted.  Every timestamp on every page
    comes from the ledger or from frontmatter.
    """
    source = (_REPO / rel).read_text(encoding="utf-8")
    hits = [tok for tok in _CLOCK_READS if tok in source]
    assert not hits, f"{rel} reads the wall clock: {hits}"


@pytest.mark.parametrize("token", sorted(_CLOCK_READS))
def test_the_clock_sentinel_is_not_vacuous(token, tmp_path):
    """A text-scanning guard that cannot see a violation is not a guard — and a
    token that no probe exercises is a token nobody has ever seen fire.

    Each probe must trip the scan through THE WHOLE TOKEN LIST, not just its own
    token: that is what catches a token whose spelling is wrong (`date.today()`
    never matched `d.today()`; `time.time(` never matched `from time import
    time`).
    """
    assert token in _CLOCK_PROBES, f"{token!r} has no probe — add one"
    probe = tmp_path / "probe.py"
    probe.write_text(_CLOCK_PROBES[token] + "\n", encoding="utf-8")
    source = probe.read_text(encoding="utf-8")
    assert [t for t in _CLOCK_READS if t in source], \
        f"probe for {token!r} tripped nothing in the sentinel"


