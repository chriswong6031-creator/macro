def test_an_empty_ledger_still_builds_a_valid_property(tmp_path):
    """An empty feed is a real state, not an error state.  Day one of a
    publication looks exactly like this."""
    root = _property_root(tmp_path, [])
    tree = tmp_path / "out"
    PR.render_property(root, P.load_config(root), "mastermind_news", dest=tree)

    for name in ("index.html", "about.html", "404.html", "feed.xml",
                 "sitemap.xml", "robots.txt", "assets/press_news.css"):
        assert (tree / name).exists(), f"missing {name}"
    assert not (tree / "articles").exists(), "no articles means no article directory"

    front = (tree / "index.html").read_text(encoding="utf-8")
    assert "<article" not in front, "an empty front page must list no articles"

    feed = ET.fromstring((tree / "feed.xml").read_text(encoding="utf-8"))
    assert feed.findall("./channel/item") == []
    assert feed.findall("./channel/lastBuildDate") == [], \
        "lastBuildDate on an item-less feed could only come from the clock"

    urls = [u.text for u in ET.fromstring(
        (tree / "sitemap.xml").read_text(encoding="utf-8")).iter(
        "{http://www.sitemaps.org/schemas/sitemap/0.9}loc")]
    assert urls == ["https://mastermindx.ai/", "https://mastermindx.ai/about.html"]

    assert (tree / "robots.txt").read_text(encoding="utf-8") == (
        "User-agent: *\nAllow: /\nSitemap: https://mastermindx.ai/sitemap.xml\n")


