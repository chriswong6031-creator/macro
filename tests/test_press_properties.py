def _property_root(tmp_path: Path, rows: list[dict] | None = None,
                   *, cutover: bool = False) -> Path:
    """A repo root carrying config, fixture templates and a press ledger."""
    import yaml

    root = tmp_path / "repo"
    (root / "config").mkdir(parents=True, exist_ok=True)
    cfg = yaml.safe_load((_REPO / "config" / "press.yml").read_text(encoding="utf-8"))
    cfg["cutover"] = bool(cutover)
    (root / "config" / "press.yml").write_text(yaml.safe_dump(cfg, sort_keys=False),
                                               encoding="utf-8")
    _write_fixture_templates(root)
    ledger = root / "data" / "press" / "published.jsonl"
    ledger.parent.mkdir(parents=True, exist_ok=True)
    ledger.write_text("".join(json.dumps(r) + "\n" for r in (rows or [])),
                      encoding="utf-8")
    (root / "content" / "seo" / "blog").mkdir(parents=True, exist_ok=True)
    return root


def _tree_bytes(tree: Path) -> dict[str, bytes]:
    return {str(p.relative_to(tree)): p.read_bytes()
            for p in sorted(tree.rglob("*")) if p.is_file()}


# ─────────────────────────────────────────────────────────────────────────────
# (a) THE CUTOVER SYNC GUARD
# ─────────────────────────────────────────────────────────────────────────────


def _caddy_lines(text: str | None = None) -> list[str]:
    return (text if text is not None
            else _CADDYFILE.read_text(encoding="utf-8")).splitlines()


def _marker_bounds(lines: list[str]) -> tuple[int, int]:
    return lines.index(_BEGIN), lines.index(_END)


def _uncommented(lines: list[str]) -> list[str]:
    """The block's interior as Caddy would see it once the cutover has happened.

    State-aware: strips one leading '#' only while the block is still commented.
    Stripping unconditionally would, after the real cutover, eat the '#' off the
    block's own inline comments and turn them into bare directives — a guard
    that reports a syntax error it invented itself.
    """
    b, e = _marker_bounds(lines)
    interior = lines[b + 1:e]
    if all(l.startswith("#") for l in interior):
        return [l[1:] for l in interior]
    return interior


def _pairing_violations(cutover: bool, caddyfile_text: str) -> list[str]:
    """THE PAIRING, as a pure function of (flag, file).

    Pure on purpose.  A guard written directly against the repo's current files
    can only ever encode the state those files are in TODAY — which is how a
    cutover guard ends up asserting that the cutover may never happen.  Written
    this way it is checked twice: once against the real files (whatever state
    they are in), and once over synthetic inputs covering all four quadrants,
    where both failure modes are actually exercised.

    Returns a list of human-readable violations; empty means consistent.
    """
    lines = _caddy_lines(caddyfile_text)
    problems: list[str] = []
    if lines.count(_BEGIN) != 1 or lines.count(_END) != 1:
        return [f"markers must appear exactly once each "
                f"(begin={lines.count(_BEGIN)}, end={lines.count(_END)})"]
    b, e = _marker_bounds(lines)
    if b >= e:
        return ["the END marker must follow the BEGIN marker"]
    interior = lines[b + 1:e]
    if not interior:
        return ["the cutover block has no interior lines"]

    # A LIVE line is a directive Caddy will act on. A '#' line is inert whatever
    # the flag says — the block carries its own prose, written '##' so that one
    # '#' survives the transform. So the state is read from the LIVE lines, not
    # from the absence of comments; a '##' line that is still '##' after a
    # cutover is the tell that the transform skipped it.
    live = [l for l in interior if l.strip() and not l.startswith("#")]
    untransformed = [l for l in interior if l.startswith("##")]
    if cutover is False and live:
        problems.append(
            "config/press.yml has `cutover: false` but these Caddyfile lines are "
            f"live: {live[:5]} — re-comment the block, or flip cutover in the SAME "
            "commit")
    if cutover is True:
        if not live:
            problems.append(
                "config/press.yml has `cutover: true` but the Caddyfile press block "
                "is still fully commented out — uncomment it in the SAME commit "
                "(see app/deploy/README.md § Press properties (W1.5))")
        elif untransformed:
            problems.append(
                "the Caddyfile press block is live but these lines never had their "
                f"leading '#' stripped: {untransformed[:5]} — the uncomment "
                "transform was applied by hand and missed them")
    return problems


# The block's committed (dark) form, in the real file's idiom: config lines get
# one '#', prose gets two so that one survives.
_SYNTHETIC_DARK = ["## the news property",
                   "#mastermindx.ai {",
                   "#\troot * /opt/macro/press_news.served",
                   "#}"]


def _synthetic(commented: bool) -> str:
    """A minimal Caddyfile carrying the marker pair in one of the two states.

    The LIVE form is DERIVED from the dark form by the same one-'#'-strip the
    runbook performs, rather than hand-written. Hand-writing it is how a
    quadrant test ends up proving something about a file shape that the real
    transform never produces — which it did, on the first attempt here: the
    hand-written "live" form left a '##' prose line that the real transform
    would have reduced to '#'.
    """
    if commented:
        return "\n".join(["# unrelated preamble", _BEGIN, *_SYNTHETIC_DARK, _END, ""])
    live = [l[1:] if l.startswith("#") else l for l in _SYNTHETIC_DARK]
    return "\n".join(["# unrelated preamble", _BEGIN, *live, _END, ""])


def test_the_cutover_markers_appear_exactly_once():
    """A duplicated marker makes every index() below silently pick the first
    pair, which is how a guard starts checking a different block than the one
    that ships."""
    text = _CADDYFILE.read_text(encoding="utf-8")
    assert text.count(_BEGIN) == 1, "PRESS-CUTOVER-BEGIN must appear exactly once"
    assert text.count(_END) == 1, "PRESS-CUTOVER-END must appear exactly once"
    lines = _caddy_lines()
    b, e = _marker_bounds(lines)
    assert b < e, "the END marker must follow the BEGIN marker"
    assert e - b > 10, "the cutover block is empty — that is not a shipped block"


def test_the_shipped_files_are_a_consistent_pair():
    """The real config + the real Caddyfile, in whatever state they are in.

    This test is state-AGNOSTIC by construction: it passes before the cutover
    and after it, and fails only on a half-flipped switch.
    """
    cutover = P.load_config(_REPO).get("cutover")
    assert cutover in (True, False), \
        f"config/press.yml cutover must be a bool, got {cutover!r}"
    problems = _pairing_violations(cutover,
                                   _CADDYFILE.read_text(encoding="utf-8"))
    assert not problems, "\n".join(problems)


@pytest.mark.parametrize("cutover,commented,legal", [
    (False, True, True),     # today: dark config, dark vhosts
    (True, False, True),     # cutover day: live config, live vhosts
    (False, False, False),   # vhosts live, nothing routed to them
    (True, True, False),     # routed emit, nothing serving it
])
def test_the_pairing_guard_catches_both_half_flips(cutover, commented, legal):
    """FOUR QUADRANTS, over synthetic inputs.

    The two legal states must PASS and the two half-flipped states must FAIL.
    A one-directional guard passes three of these four and lets exactly one
    disaster through — and which one depends on which direction was written,
    which is not a property anybody remembers a year later.
    """
    problems = _pairing_violations(cutover, _synthetic(commented))
    if legal:
        assert not problems, f"a legal state was rejected: {problems}"
    else:
        assert problems, (
            f"half-flipped state (cutover={cutover}, commented={commented}) "
            "was accepted — the guard is one-directional")


def test_the_pairing_guard_rejects_a_duplicated_marker():
    """A duplicated marker makes every index() pick the first pair, which is how
    a guard starts checking a different block than the one that ships."""
    doubled = _synthetic(True) + _synthetic(True)
    assert _pairing_violations(False, doubled)


def test_the_uncommented_block_is_the_config_we_intend_to_serve():
    """What `sed 's/^#//'` produces has to be the real thing, not approximately
    it: nobody reads a commented block as configuration, so this is the only
    place its shape is ever checked before it goes live."""
    block = "\n".join(_uncommented(_caddy_lines()))
    directives = "\n".join(l for l in block.splitlines() if not l.lstrip().startswith("#"))

    assert directives.count("{") == directives.count("}"), \
        "unbalanced braces in the cutover block"
    assert "\nblog.mastermind-x.com {" in "\n" + directives
    assert "root * /opt/macro/press_news.served" in directives
    assert "root * /opt/macro/press_research.served" in directives

    # ONE CANONICAL HOST: the apex serves, www 301s to it. Serving both names
    # off one block puts every page on two live URLs and leaves rel=canonical —
    # a hint, not an instruction — to sort it out.
    assert "\nmastermindx.ai {" in "\n" + directives, "the apex must be its own site block"
    assert "mastermindx.ai, www.mastermindx.ai {" not in directives, \
        "apex and www must not share one serving block"
    assert "www.mastermindx.ai {\n" in directives
    assert "redir https://mastermindx.ai{uri} permanent" in directives, \
        "www must 301 to the apex — the host config/press.yml base_url names"

    # REAL certificates. These hosts are grey-cloud direct A records with no CDN
    # in front, so `tls internal` would hand a browser a self-signed cert.
    assert "tls internal" not in directives, (
        "the press vhosts are direct/grey-cloud — they take real Let's Encrypt "
        "certs over HTTP-01, never `tls internal`")

    assert directives.count("Content-Security-Policy") == 2, "both vhosts need a CSP"
    assert "frame-ancestors 'none'" in directives
    assert "X-Content-Type-Options" in directives and "X-Frame-Options" in directives

    # HSTS RAMP. A long max-age on a brand-new host is not revocable: a client
    # that cached it refuses plain http until it expires, so a cert or DNS
    # mistake is unreachable-by-design. Ship 300s, raise it after a clean week.
    hsts = re.findall(r'Strict-Transport-Security "max-age=(\d+)"', directives)
    assert hsts, "both vhosts need HSTS"
    assert all(int(v) <= 300 for v in hsts), (
        f"press vhosts ship an un-revocable HSTS max-age {hsts} on day one — "
        "start at 300 and raise it in a follow-up (app/deploy/README.md step 5)")

    # `auto_https disable_redirects` is global, so each host needs its own.
    for host in ("http://mastermindx.ai", "http://www.mastermindx.ai",
                 "http://blog.mastermind-x.com"):
        assert f"{host} {{" in directives, \
            f"missing the plain-HTTP redirect block for {host}"
    assert directives.count("redir https://") == 4, \
        "three http->https redirects plus the www->apex canonical redirect"

    assert "max-age=31536000, immutable" in directives, \
        "versioned assets need the immutable cache"
    assert "handle_errors" in directives and "/404.html" in directives


def test_block_comments_survive_the_uncomment_as_comments():
    """A prose line inside the block must carry a DOUBLE '#'.

    THE DEFECT THIS CLOSES, found by running the real `caddy validate` on the
    transformed file: a single-'#' comment inside the block loses its '#' to the
    uncomment and becomes a bare line, which Caddy reads as a SITE ADDRESS
    ("Site addresses cannot contain a comma"). The cutover would have failed
    validation on the box — where the only symptom is update.sh refusing to
    install the new config, at 3am, silently.

    Checked structurally rather than by guessing which lines look like prose:
    in Caddyfile grammar every line at brace-depth 0 opens a site block and
    therefore ends in '{'. A surviving comment lands at depth 0 and does not.
    """
    depth = 0
    for line in _uncommented(_caddy_lines()):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            depth += line.count("{") - line.count("}")
            continue
        if depth == 0:
            assert stripped.endswith("{"), (
                f"line {stripped!r} sits at brace-depth 0 after the uncomment but does "
                "not open a site block — Caddy reads it as a site address. Prose inside "
                "the block must use '##' so one '#' survives the transform.")
        depth += line.count("{") - line.count("}")
        assert depth >= 0, f"unbalanced closing brace at {stripped!r}"
    assert depth == 0, "the uncommented block does not close every brace it opens"


