@pytest.mark.parametrize("pub_key,prefix", [("mastermind_news", "news"),
                                            ("mastermind_research", "research")])
def test_real_templates_render_a_compliant_page(pub_key, prefix, tmp_path, capsys):
    """THE LIVE INTEGRATION GATE — the one test that renders the real templates.

    Deliberately NOT skip-guarded: a skip-guarded integration test is an unrun
    test that reads green, which is how a renderer and a template set ship in
    the same PR having never met.  It asserts the four things the renderer
    cannot check about itself:

      * the standing disclosure reaches the page, verbatim, EXACTLY ONCE (twice
        means the body still carries its estate chrome — see M1);
      * the byline appears exactly once for the same reason;
      * the page declares its canonical URL;
      * the JSON-LD block parses (an autoescaped one parses as nothing at all).
    """
    root, tree, cfg = _populated(tmp_path)
    shutil.rmtree(root / "templates" / "press")
    shutil.copytree(_REPO / "templates" / "press", root / "templates" / "press")

    if pub_key == "mastermind_research":
        # Same fixture archive, re-pointed at the research property. The native
        # piece's .md moves to the research content_dir too — a publication only
        # searches its OWN content_dir plus the flagship estate.
        led = root / "data" / "press" / "published.jsonl"
        rows = [json.loads(l) for l in led.read_text(encoding="utf-8").splitlines()]
        url = "https://blog.mastermind-x.com/articles/native-note.html"
        for r in rows:
            r["publication"] = "mastermind_research"
            if r["slug"] == "native-note":
                r["url"] = url
        led.write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")
        dst = root / "content" / "press" / "research" / "native-note.md"
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / "content" / "press" / "news" / "native-note.md", dst)

    PR.render_property(root, cfg, pub_key, dest=tree)
    capsys.readouterr()

    article_rel = "articles/native-note.html"
    footer = cfg["validators"]["footer_required_text"]
    for name in ("index.html", "about.html", "404.html", article_rel):
        page = (tree / name).read_text(encoding="utf-8")
        assert page.count(footer) == 1, (
            f"{prefix} {name}: the standing disclosure appears {page.count(footer)} "
            "times — it must appear exactly once (twice means the article body "
            "still carries the estate's in-body footer)")

    article = (tree / article_rel).read_text(encoding="utf-8")
    byline = cfg["desks"]["brief"]["byline"]      # every fixture row is brief's
    # Count VISIBLE occurrences only: the JSON-LD block legitimately names the
    # desk as `author.name`, and that is machine-readable metadata, not chrome.
    visible = re.sub(r'<script type="application/ld\+json">.*?</script>', "",
                     article, flags=re.DOTALL)
    visible = visible[visible.index("<body"):]
    assert visible.count(byline) == 1, (
        f"{prefix}: the byline appears {visible.count(byline)} times in the visible "
        "page — the template draws it, so the body must not carry it too")

    expected_url = PR.iter_publication_articles(root, cfg, pub_key)[0]["url"]
    assert f'rel="canonical" href="{expected_url}"' in article.replace("'", '"'), \
        "the article page must declare its canonical URL"

    raw = re.search(r'<script type="application/ld\+json">(.*?)</script>',
                    article, re.DOTALL).group(1)
    data = json.loads(raw)     # an escaped JSON-LD block dies here
    assert data["@type"] == ("NewsArticle" if pub_key == "mastermind_news"
                             else "Article")


