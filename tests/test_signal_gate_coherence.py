def _gate_entry(**over) -> dict:
    """One signal_gate.json verdict: the 11 keys the live artifact carries."""
    e = {
        "anchor_era": "2026-07-30", "bars_to_cross": 0, "eligible": True,
        "htf_s1": True, "htf_s2": False, "provisional": False,
        "sq_anchor_era": "2026-07-28", "ticks": 3, "tier_cascade": "T2",
        "tier_sub": "confirmed", "young_history": False,
    }
    e.update(over)
    return e


def _blob(**over) -> dict:
    """A board row's embedded `signal` blob: a strict SUPERSET of the gate entry."""
    b = _gate_entry()
    b.update({
        "asof": "2026-08-12", "state": "FRESH BUY", "tier": "T2", "sub": "confirmed",
        "weight": 1.0, "reason": "confluence", "reasons": [], "above200": True,
        "early_now": False, "fresh_bars": 2, "history_bars": 900, "last": 101.5,
        "weekly_bull": True,
    })
    b.update(over)
    return b


def _standouts(*, buy=(), watch=(), leaders=(), laggards=(), **top) -> dict:
    d = {"as_of": "2026-08-12", "rank_by": "us_prophet_v1",
         "buy": list(buy), "watch": list(watch),
         "leaders": list(leaders), "laggards": list(laggards)}
    d.update(top)
    return d


def _gate(entries: dict, **top) -> dict:
    d = {"as_of": "2026-08-12", "verdicts": entries}
    d.update(top)
    return d


def _row(ticker: str, sig: dict | None) -> dict:
    return {"ticker": ticker, "alpha": 0.4, "state": "FRESH BUY", "signal": sig}


def _write_pair(tmp_path: Path, standouts: dict, gate: dict) -> tuple[str, str]:
    fd = tmp_path / "factordata"
    fd.mkdir(parents=True, exist_ok=True)
    p_s, p_g = fd / "us_standouts.json", fd / "signal_gate.json"
    p_s.write_text(json.dumps(standouts))
    p_g.write_text(json.dumps(gate))
    return str(p_s), str(p_g)


# The 2026-08-12 incident: 8 of 69 buy rows disagreed with the gate on `ticks`.
_SKEWED_5490 = ("CRCL", "GPCR", "GRAB", "LNG", "NTES", "RBRK", "SGML", "TEM")


def _incident_pair() -> tuple[dict, dict]:
    """The #5490 shape: a board re-emitted with fresh blobs against an unadvanced gate."""
    rows = [_row(t, _blob(ticks=0 if t == "NTES" else 1)) for t in _SKEWED_5490]
    rows.append(_row("AAPL", _blob()))          # coherent control
    gate = {t: _gate_entry(ticks=3) for t in _SKEWED_5490}
    gate["AAPL"] = _gate_entry()
    return _standouts(buy=rows), _gate(gate)


# ---------------------------------------------------------------------------
# 1. a coherent pair is clean
# ---------------------------------------------------------------------------

class TestCoherentPair:
    def test_predicate_empty_on_coherent_pair(self):
        s = _standouts(buy=[_row("AAPL", _blob())], watch=[_row("MSFT", _blob(ticks=5))],
                       leaders=[_row("NVDA", _blob(tier_cascade="T1"))],
                       laggards=[_row("INTC", _blob(eligible=False))])
        g = _gate({"AAPL": _gate_entry(), "MSFT": _gate_entry(ticks=5),
                   "NVDA": _gate_entry(tier_cascade="T1"),
                   "INTC": _gate_entry(eligible=False)})
        assert incoherent_tickers(s, g) == {}

    def test_check_returns_no_violations(self, tmp_path):
        s = _standouts(buy=[_row("AAPL", _blob())])
        g = _gate({"AAPL": _gate_entry()})
        assert _check(*_write_pair(tmp_path, s, g)) == []

    def test_blob_superset_keys_are_not_a_violation(self):
        """The gate entry's own key set is the contract — extra blob keys must not red."""
        s = _standouts(buy=[_row("AAPL", _blob(some_new_display_field="x"))])
        assert incoherent_tickers(s, _gate({"AAPL": _gate_entry()})) == {}


