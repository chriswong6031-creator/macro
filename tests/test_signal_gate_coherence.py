class TestIncidentShape:
    def test_exactly_the_skewed_tickers_are_flagged(self):
        s, g = _incident_pair()
        assert incoherent_tickers(s, g) == {t: ["ticks"] for t in _SKEWED_5490}

    def test_check_strings_name_every_skewed_ticker_and_both_values(self, tmp_path):
        s, g = _incident_pair()
        viol = _check(*_write_pair(tmp_path, s, g))
        assert len(viol) == len(_SKEWED_5490)
        text = "\n".join(viol)
        for t in _SKEWED_5490:
            assert t in text
        assert "AAPL" not in text
        assert "NTES: 1 gate key(s) disagree — ticks: board=0 gate=3" in text

    def test_cli_exits_1_on_the_incident_pair(self, tmp_path, capsys):
        s, g = _incident_pair()
        p_s, p_g = _write_pair(tmp_path, s, g)
        assert cli_main([p_s, p_g]) == 1
        assert "NTES" in capsys.readouterr().err


