"""tests/test_signal_gate_coherence.py — the board/gate pair must be one run's work.

Guards scripts/check_signal_gate_coherence.py and the two readers that demote a stale gate
(scripts/build_discovery._signal_verdicts, scripts/run_watchlist_sentinel._load_per_ticker_states).

Every fixture here is a LITERAL dict, never a call into build_stock_library. That is the
point: the artifacts are what disagreed on 2026-08-12, so a fixture generated by the writer
could never express the failure — it would agree with itself by construction.
"""
