class TestPredicateCoversEveryGateKey:
    @pytest.mark.parametrize("key,board_value,gate_value", [
        ("tier_cascade", "T3", "T1"),
        ("tier_sub", "provisional", "confirmed"),
        ("eligible", False, True),
        ("anchor_era", "2026-08-01", "2026-07-30"),
        ("bars_to_cross", 4, 0),
        ("htf_s1", False, True),
        ("young_history", True, False),
    ])
    def test_skew_on_a_non_ticks_key_is_still_flagged(self, key, board_value, gate_value):
        """A ticks-only predicate would read GREEN here — the whole gate entry is the contract."""
        s = _standouts(buy=[_row("AAPL", _blob(**{key: board_value}))])
        g = _gate({"AAPL": _gate_entry(**{key: gate_value})})
        assert incoherent_tickers(s, g) == {"AAPL": [key]}

    def test_multi_key_skew_reports_every_key(self):
        s = _standouts(buy=[_row("AAPL", _blob(ticks=0, tier_cascade="T3", eligible=False))])
        g = _gate({"AAPL": _gate_entry(ticks=3, tier_cascade="T1", eligible=True)})
        assert incoherent_tickers(s, g) == {"AAPL": ["eligible", "ticks", "tier_cascade"]}

    def test_every_bucket_is_graded(self):
        """A stale gate skews whatever names it reaches — not just the buy lane."""
        for bucket in ("buy", "watch", "leaders", "laggards"):
            s = _standouts(**{bucket: [_row("AAPL", _blob(ticks=0))]})
            assert incoherent_tickers(s, _gate({"AAPL": _gate_entry(ticks=3)})) == \
                {"AAPL": ["ticks"]}, f"{bucket} rows must be graded"
