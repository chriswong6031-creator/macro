class TestSentinelDemotion:
    def _fixture(self, tmp_path, monkeypatch):
        from scripts import run_watchlist_sentinel as rws

        # NTES: board row disagrees with the gate -> flagged, row values win.
        # AAPL: EMPTY blob -> skipped by the predicate, so the gate keeps its preference
        #       (and the row carries no gate fields at all, which makes the source visible).
        s = _standouts(buy=[_row("NTES", _blob(eligible=False, tier_cascade="T3"))],
                       watch=[_row("AAPL", {})])
        g = _gate({"NTES": _gate_entry(eligible=True, tier_cascade="T1"),
                   "AAPL": _gate_entry(eligible=True, tier_cascade="T2")})
        _write_pair(tmp_path / "site", s, g)
        monkeypatch.setattr(rws, "ROOT", tmp_path)
        monkeypatch.setattr(rws._eb, "store_staleness", lambda: {"stale": True})
        return rws

    def test_flagged_ticker_uses_row_values_unflagged_uses_gate(self, tmp_path, monkeypatch):
        rws = self._fixture(tmp_path, monkeypatch)
        states = rws._load_per_ticker_states("2026-08-12")

        assert states["NTES"]["gate_tier"] == "T3", "flagged name must read the board row"
        assert states["NTES"]["gate_eligible"] is False
        assert states["AAPL"]["gate_tier"] == "T2", "coherent name still prefers the gate"
        assert states["AAPL"]["gate_eligible"] is True

    def test_warning_is_a_line_start_annotation(self, tmp_path, monkeypatch, capsys):
        rws = self._fixture(tmp_path, monkeypatch)
        rws._load_per_ticker_states("2026-08-12")
        line = next(ln for ln in capsys.readouterr().out.splitlines() if "coherence" in ln)
        assert line.startswith("::")
        assert line.startswith("::warning title=signal-gate-coherence")
        assert "NTES" in line

    def test_coherent_pair_is_silent(self, tmp_path, monkeypatch, capsys):
        from scripts import run_watchlist_sentinel as rws

        _write_pair(tmp_path / "site", _standouts(buy=[_row("AAPL", _blob())]),
                    _gate({"AAPL": _gate_entry()}))
        monkeypatch.setattr(rws, "ROOT", tmp_path)
        monkeypatch.setattr(rws._eb, "store_staleness", lambda: {"stale": True})
        states = rws._load_per_ticker_states("2026-08-12")
        assert states["AAPL"]["gate_tier"] == "T2"
        assert "signal-gate-coherence" not in capsys.readouterr().out


