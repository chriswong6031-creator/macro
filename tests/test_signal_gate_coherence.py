# 5. lineage: the emit stamp names the stale side, and only skew is a violation
# ---------------------------------------------------------------------------

def _stamp(pair_id: str, at_utc: str) -> dict:
    return {"pair_id": pair_id, "at_utc": at_utc, "writer": "build_stock_library"}


class TestLineageStamp:
    def test_differing_pair_id_with_identical_content_is_benign(self, tmp_path):
        """A re-emit that changed nothing is not a violation — only disagreement is."""
        s = _standouts(buy=[_row("AAPL", _blob())],
                       emit=_stamp("bbbb", "2026-08-12T22:40:00+00:00"))
        g = _gate({"AAPL": _gate_entry()}, emit=_stamp("aaaa", "2026-08-12T02:10:00+00:00"))
        assert _check(*_write_pair(tmp_path, s, g)) == []

    def test_differing_pair_id_with_skew_names_the_older_side_as_stale(self, tmp_path):
        s, g = _incident_pair()
        s["emit"] = _stamp("bbbb", "2026-08-12T22:40:00+00:00")
        g["emit"] = _stamp("aaaa", "2026-08-12T02:10:00+00:00")   # the gate lagged
        viol = _check(*_write_pair(tmp_path, s, g))
        lineage = [v for v in viol if v.startswith("lineage:")]
        assert len(lineage) == 1
        assert "signal_gate.json is the STALE side" in lineage[0]
        assert "us_standouts.json" in lineage[0]

    def test_same_pair_id_emits_no_lineage_line(self, tmp_path):
        """One run wrote both files, so nothing lags — the skew is reported without direction."""
        s, g = _incident_pair()
        s["emit"] = g["emit"] = _stamp("cccc", "2026-08-12T22:40:00+00:00")
        assert [v for v in _check(*_write_pair(tmp_path, s, g)) if v.startswith("lineage:")] == []


