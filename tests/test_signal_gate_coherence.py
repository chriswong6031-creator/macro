class TestDiscoveryDemotion:
    def test_flagged_verdict_becomes_the_board_blob(self, tmp_path, capsys):
        from scripts import build_discovery as bd

        blob = _blob(ticks=0, tier_cascade="T3")
        s = _standouts(buy=[_row("NTES", blob), _row("AAPL", _blob())])
        g = _gate({"NTES": _gate_entry(ticks=3), "AAPL": _gate_entry()})
        _write_pair(tmp_path, s, g)

        v = bd._signal_verdicts(tmp_path, None)

        assert v["NTES"] == blob, "the board's fresher copy must replace the stale verdict"
        assert v["AAPL"] == _gate_entry(), "a coherent name keeps its gate verdict untouched"
        # house law: the annotation must START the line (never through a logger)
        line = next(ln for ln in capsys.readouterr().out.splitlines() if "coherence" in ln)
        assert line.startswith("::")
        assert line.startswith("::warning title=signal-gate-coherence")
        assert "NTES" in line

    def test_absent_from_gate_ticker_is_added(self, tmp_path):
        from scripts import build_discovery as bd

        blob = _blob(tier_cascade="T1")
        _write_pair(tmp_path, _standouts(buy=[_row("AAPL", _blob()), _row("GHOST", blob)]),
                    _gate({"AAPL": _gate_entry()}))
        v = bd._signal_verdicts(tmp_path, None)
        assert v["GHOST"] == blob

    def test_coherent_pair_leaves_the_verdicts_untouched_and_silent(self, tmp_path, capsys):
        from scripts import build_discovery as bd

        _write_pair(tmp_path, _standouts(buy=[_row("AAPL", _blob())]),
                    _gate({"AAPL": _gate_entry()}))
        v = bd._signal_verdicts(tmp_path, None)
        assert v == {"AAPL": _gate_entry()}
        assert "signal-gate-coherence" not in capsys.readouterr().out


