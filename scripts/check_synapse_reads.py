"""
scripts/check_synapse_reads.py — Synapse read-gate: literal-path scan v1.

For every artifact registered in config/synapse.yml, scans engine/*.py,
scripts/*.py, and collectors/*.py for string literals that contain the
artifact's path (or its directory prefix for per-ticker pattern paths).
Undeclared readers — modules that reference the path but are NOT the registered
producer, a known_extra_writer, or a declared consumer — are findings.

Two severity tiers:
  WARN (exit 0):  any undeclared reader → print + GitHub ::warning:: annotation.
  HARD FAIL (exit 1): an undeclared reader that is an Article-2 surface module
                       (the money-path set defined in synapse.yml meta.article2_surfaces).

Baseline (data/neuralweb/read_gate_baseline.json):
  Generated by --write-baseline; contains the snapshot of ALL findings at time
  of generation, sorted for determinism. Normal runs suppress baseline entries
  and print their count. New findings (not in baseline) are warned/failed.
  Stale baseline entries (in baseline but no longer firing) are printed as
  'stale baseline entry — prune'.

Usage
-----
  python scripts/check_synapse_reads.py [--root PATH] [--write-baseline] [--selftest]

Options
-------
  --root PATH         Repo root (default: parent of scripts/).
  --write-baseline    Scan all files, write findings to baseline, exit 0.
  --selftest          Inject a synthetic module with an undeclared read and prove
                      both WARN and HARD FAIL findings are detected. Exit 0 on pass.

Article-2 surface→module mapping (money-path set):
  alert_triage     -> engine/alert_triage.py
  board_ordering   -> scripts/build_stock_library.py
  top_setups       -> scripts/build_site.py
  attention_queue  -> []  (future cortex/reflex modules; no module yet)
  push_floor       -> []  (future push-notification floor; no module yet)

Scan scope:
  engine/*.py, scripts/*.py, collectors/*.py
  Excludes: __pycache__, this script itself, check_synapse_registry.py

IMPORTANT HONESTY RULE: this is a LITERAL-PATH scan (string literals in source).
It does NOT trace runtime file-access paths, AST data-flow, or dynamic open()
calls. A module that builds a path via os.path.join() without a matching literal
will NOT be detected by v1. AST data-flow tracing is deferred to a later wave.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from pathlib import Path
from typing import NamedTuple

# Allow running as a standalone script from the repo root.
_HERE = Path(__file__).resolve().parent
_REPO_ROOT = _HERE.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from engine.neuralweb.synapse import load_registry  # noqa: E402

# ---------------------------------------------------------------------------
# Article-2 surface → module mapping (money-path)
# ---------------------------------------------------------------------------
# Derived from synapse.yml meta.article2_surfaces. Each surface maps to the
# concrete module files that implement it.
# attention_queue -> [] (future cortex/reflex modules; no file yet)
# push_floor      -> [] (future push-notification reflex; no file yet)

_ARTICLE2_MAP: dict[str, list[str]] = {
    "alert_triage": ["engine/alert_triage.py"],
    "board_ordering": ["scripts/build_stock_library.py"],
    "top_setups": ["scripts/build_site.py"],
    "attention_queue": [],   # future cortex/reflex module — not yet created
    "push_floor": [],        # future push-notification floor — not yet created
}

# ---------------------------------------------------------------------------
# Baseline path
# ---------------------------------------------------------------------------

_BASELINE_PATH_REL = "data/neuralweb/read_gate_baseline.json"

# ---------------------------------------------------------------------------
# Finding data structure
# ---------------------------------------------------------------------------


class Finding(NamedTuple):
    module: str       # repo-relative path, e.g. "engine/foo.py"
    artifact_id: str
    line_no: int
    severity: str     # "WARN" or "HARD"

    def as_dict(self) -> dict:
        return {
            "module": self.module,
            "artifact_id": self.artifact_id,
            "line_no": self.line_no,
            "severity": self.severity,
        }

    def baseline_key(self) -> tuple:
        """Stable sort key for baseline comparison (line_no excluded — files change)."""
        return (self.module, self.artifact_id)

    @classmethod
    def from_dict(cls, d: dict) -> "Finding":
        return cls(
            module=d["module"],
            artifact_id=d["artifact_id"],
            line_no=d.get("line_no", 0),
            severity=d["severity"],
        )


# ---------------------------------------------------------------------------
# Path normalization helpers
# ---------------------------------------------------------------------------

_PLACEHOLDER_RE = re.compile(r"<[A-Z_]+>")


def _normalize_search_path(path: str) -> str:
    """
    For a registered artifact path, produce the string literal we search for.

    Per-ticker pattern paths (containing <SYM>-style placeholders) are
    reduced to their directory prefix, e.g.:
      "site/signals/<SYM>.json"  ->  "site/signals/"
    Plain paths are returned as-is.
    """
    m = _PLACEHOLDER_RE.search(path)
    if not m:
        return path
    # Strip from the first placeholder onward; keep the dir prefix including trailing /
    before = path[: m.start()]
    # Ensure we end at a directory boundary
    slash_pos = before.rfind("/")
    if slash_pos >= 0:
        return before[: slash_pos + 1]
    return before


# ---------------------------------------------------------------------------
# Module discovery
# ---------------------------------------------------------------------------

_THIS_SCRIPT = Path(__file__).name
_REGISTRY_SCRIPT = "check_synapse_registry.py"


def _scan_dirs(root: Path) -> list[Path]:
    """Return all .py files in engine/, scripts/, collectors/ (excluding __pycache__)."""
    files: list[Path] = []
    for subdir in ("engine", "scripts", "collectors"):
        d = root / subdir
        if not d.is_dir():
            continue
        for f in sorted(d.rglob("*.py")):
            if "__pycache__" in f.parts:
                continue
            if f.name in (_THIS_SCRIPT, _REGISTRY_SCRIPT):
                continue
            files.append(f)
    return files


# ---------------------------------------------------------------------------
# Article-2 module set builder
# ---------------------------------------------------------------------------


def _build_article2_modules(root: Path, reg: dict) -> set[str]:
    """
    Return the set of repo-relative module paths that are Article-2 surfaces.
    Derives the surface list from meta.article2_surfaces and looks them up in
    _ARTICLE2_MAP for the concrete file names.
    """
    surfaces = (reg.get("meta") or {}).get("article2_surfaces") or []
    modules: set[str] = set()
    for surface in surfaces:
        for mod in _ARTICLE2_MAP.get(surface, []):
            modules.add(mod)
    return modules


# ---------------------------------------------------------------------------
# Scanner core
# ---------------------------------------------------------------------------


def scan_findings(
    root: Path,
    reg: dict | None = None,
    extra_files: dict[str, str] | None = None,
) -> list[Finding]:
    """
    Scan for undeclared readers of registered artifacts.

    Parameters
    ----------
    root        : Repo root path.
    reg         : Parsed registry dict (loaded from synapse.yml if None).
    extra_files : Optional dict of {repo-relative-path: source_text} for
                  synthetic files (used by selftest and unit tests).
                  When provided, ONLY these files are scanned (not disk).

    Returns
    -------
    List of Finding objects, sorted by (module, artifact_id).
    """
    if reg is None:
        reg = load_registry(root)

    artifacts = reg.get("artifacts") or {}
    article2_modules = _build_article2_modules(root, reg)

    # Build per-artifact search config
    # Each entry: {artifact_id, search_path, producer_rel, declared_set, extra_writers_set}
    artifact_configs: list[dict] = []
    for art_id, entry in artifacts.items():
        if not isinstance(entry, dict):
            continue
        raw_path = entry.get("path", "")
        if not raw_path:
            continue

        search_path = _normalize_search_path(raw_path)

        # Registered producer (may include line reference like "engine/run.py:705")
        producer_raw = entry.get("producer", "") or ""
        producer_rel = producer_raw.split(":")[0].strip()

        # known_extra_writers: each entry is "scripts/foo.py — description"
        extra_writers: set[str] = set()
        for ew in (entry.get("known_extra_writers") or []):
            if isinstance(ew, str):
                mod = ew.split("—")[0].strip().split(" ")[0].strip()
                if mod:
                    extra_writers.add(mod)

        # declared consumers
        consumers: set[str] = set(entry.get("consumers") or [])

        artifact_configs.append({
            "artifact_id": art_id,
            "search_path": search_path,
            "producer_rel": producer_rel,
            "extra_writers": extra_writers,
            "consumers": consumers,
        })

    # Determine files to scan
    if extra_files is not None:
        # Synthetic mode: only scan the provided text
        file_iter: list[tuple[str, str]] = list(extra_files.items())
    else:
        # Real disk scan
        disk_files = _scan_dirs(root)
        file_iter = []
        for fp in disk_files:
            rel = str(fp.relative_to(root))
            try:
                text = fp.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            file_iter.append((rel, text))

    findings: list[Finding] = []

    for rel_path, source_text in file_iter:
        # Normalize path separators
        mod = rel_path.replace("\\", "/")

        for ac in artifact_configs:
            search_path = ac["search_path"]
            # Quick pre-check: path string present at all?
            if search_path not in source_text:
                continue

            # Skip registered producer
            if mod == ac["producer_rel"]:
                continue
            # Skip known extra writers
            if mod in ac["extra_writers"]:
                continue
            # Skip declared consumers
            if mod in ac["consumers"]:
                continue

            # Confirmed undeclared reader — find line numbers
            lines = source_text.splitlines()
            found_lines: list[int] = []
            for i, line in enumerate(lines, start=1):
                if search_path in line:
                    found_lines.append(i)

            if not found_lines:
                continue

            # Determine severity
            severity = "HARD" if mod in article2_modules else "WARN"

            # One finding per first match line (grouping by module+artifact)
            findings.append(
                Finding(
                    module=mod,
                    artifact_id=ac["artifact_id"],
                    line_no=found_lines[0],
                    severity=severity,
                )
            )

    # Sort deterministically
    findings.sort(key=lambda f: (f.module, f.artifact_id, f.line_no))
    return findings


# ---------------------------------------------------------------------------
# Baseline helpers
# ---------------------------------------------------------------------------


def _baseline_key(f: Finding) -> str:
    """Compact string key for baseline membership test."""
    return f"{f.module}|{f.artifact_id}"


def _load_baseline(root: Path) -> dict[str, dict] | None:
    """Load baseline from disk. Returns None if file doesn't exist."""
    bp = root / _BASELINE_PATH_REL
    if not bp.exists():
        return None
    with open(bp, encoding="utf-8") as fh:
        raw = json.load(fh)
    # Index by baseline_key for fast lookup
    return {f"{e['module']}|{e['artifact_id']}": e for e in raw.get("findings", [])}


def _write_baseline(root: Path, findings: list[Finding]) -> None:
    """Write findings to the baseline file, sorted for determinism."""
    bp = root / _BASELINE_PATH_REL
    bp.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "schema": "synapse-read-gate-baseline-v1",
        "description": (
            "Snapshot of all undeclared-reader findings at baseline generation time. "
            "Only-shrinks ratchet: new findings that do NOT appear here trigger "
            "WARN or HARD FAIL. Stale entries (no longer firing) are reported as "
            "'stale baseline entry — prune'."
        ),
        "findings": [f.as_dict() for f in sorted(findings, key=lambda f: (f.module, f.artifact_id, f.line_no))],
    }
    with open(bp, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
    print(f"baseline written: {bp} ({len(findings)} findings)")


# ---------------------------------------------------------------------------
# Output / annotation helpers
# ---------------------------------------------------------------------------


def _github_annotation(severity: str, path: str, line: int, message: str) -> str:
    level = "error" if severity == "HARD" else "warning"
    return f"::{level} file={path},line={line}::{message}"


def _report_findings(
    findings: list[Finding],
    baseline: dict[str, dict] | None,
    root: Path,
) -> tuple[int, int]:
    """
    Print findings and GitHub annotations; return (n_new_warn, n_new_hard).

    Baseline entries that no longer fire are printed as 'stale baseline entry — prune'.
    """
    n_suppressed = 0
    new_findings: list[Finding] = []

    fired_keys: set[str] = set()

    for f in findings:
        key = _baseline_key(f)
        fired_keys.add(key)
        if baseline is not None and key in baseline:
            n_suppressed += 1
        else:
            new_findings.append(f)

    # Print stale baseline entries
    if baseline is not None:
        for key, entry in sorted(baseline.items()):
            if key not in fired_keys:
                print(f"stale baseline entry — prune: {entry['module']} / {entry['artifact_id']}")

    if n_suppressed:
        print(f"  ({n_suppressed} baseline-suppressed finding(s) — run --write-baseline to update)")

    n_warn = 0
    n_hard = 0
    for f in new_findings:
        msg = (
            f"undeclared reader: {f.module!r} reads artifact {f.artifact_id!r} "
            f"(path literal) but is not declared as a consumer"
        )
        if f.severity == "HARD":
            msg += " [Article-2 HARD FAIL — money-path surface]"
            n_hard += 1
        else:
            n_warn += 1

        print(f"  [{f.severity}] {f.module}:{f.line_no} → {f.artifact_id}")
        print(f"         {msg}")
        print(_github_annotation(f.severity, f.module, f.line_no, msg))

    return n_warn, n_hard


# ---------------------------------------------------------------------------
# Self-test
# ---------------------------------------------------------------------------

def _run_selftest(root: Path) -> int:
    """
    Inject synthetic module texts and prove WARN + HARD findings are detected.
    Returns 0 on pass, 1 on failure.
    """
    reg = load_registry(root)
    artifacts = reg.get("artifacts") or {}

    # Pick a real artifact with a non-pattern path to use as test target
    target_art_id: str | None = None
    target_path: str | None = None
    for art_id, entry in artifacts.items():
        if not isinstance(entry, dict):
            continue
        p = entry.get("path", "")
        if p and "<" not in p and "site/" not in p:  # prefer a data/ path
            target_art_id = art_id
            target_path = p
            break

    if target_art_id is None or target_path is None:
        print("selftest FAIL — could not find a suitable artifact for synthetic test")
        return 1

    print(f"selftest: using artifact {target_art_id!r} (path {target_path!r})")

    all_passed = True

    # ---- Test 1: undeclared reader -> WARN finding ----
    synthetic_warn = {
        "engine/_selftest_warn.py": textwrap.dedent(f"""\
            # synthetic undeclared reader — WARN
            import json
            path = "{target_path}"
            data = json.load(open(path))
        """),
    }
    warn_findings = scan_findings(root, reg=reg, extra_files=synthetic_warn)
    warn_match = any(
        f.artifact_id == target_art_id
        and f.severity == "WARN"
        and f.module == "engine/_selftest_warn.py"
        for f in warn_findings
    )
    status = "PASS" if warn_match else "FAIL"
    if not warn_match:
        all_passed = False
    print(f"  selftest [{status}] undeclared reader -> WARN (module not in Article-2)")
    if not warn_match:
        print(f"    findings returned: {warn_findings}")

    # ---- Test 2: Article-2 surface undeclared reader -> HARD finding ----
    # Use a module path that IS in our article2 map
    # alert_triage is an Article-2 surface mapped to engine/alert_triage.py
    article2_mod = "engine/alert_triage.py"
    # Check the artifact is NOT already declared as consumer in alert_triage
    target_entry = artifacts.get(target_art_id, {})
    declared_consumers = set(target_entry.get("consumers") or [])
    # If alert_triage is already a declared consumer, pick a different artifact
    art2_target_id = target_art_id
    art2_target_path = target_path
    if article2_mod in declared_consumers:
        for art_id, entry in artifacts.items():
            if not isinstance(entry, dict):
                continue
            p = entry.get("path", "")
            if p and "<" not in p and "site/" not in p:
                consumers_here = set(entry.get("consumers") or [])
                if article2_mod not in consumers_here and art_id != art2_target_id:
                    producer = (entry.get("producer") or "").split(":")[0].strip()
                    if article2_mod != producer:
                        art2_target_id = art_id
                        art2_target_path = p
                        break

    synthetic_hard = {
        article2_mod: textwrap.dedent(f"""\
            # synthetic undeclared reader in Article-2 surface — HARD
            import json
            path = "{art2_target_path}"
            data = json.load(open(path))
        """),
    }
    hard_findings = scan_findings(root, reg=reg, extra_files=synthetic_hard)
    hard_match = any(
        f.artifact_id == art2_target_id
        and f.severity == "HARD"
        and f.module == article2_mod
        for f in hard_findings
    )
    status = "PASS" if hard_match else "FAIL"
    if not hard_match:
        all_passed = False
    print(f"  selftest [{status}] Article-2 undeclared reader -> HARD (engine/alert_triage.py)")
    if not hard_match:
        print(f"    target: artifact={art2_target_id!r} path={art2_target_path!r}")
        print(f"    findings returned: {hard_findings}")

    # ---- Test 3: declared consumer -> clean ----
    # Build a synthetic file for a declared consumer of target_art_id
    # Use the first declared consumer that starts with "engine/" or "scripts/"
    declared_consumer_mod: str | None = None
    for cons in declared_consumers:
        if cons.startswith(("engine/", "scripts/")):
            declared_consumer_mod = cons
            break

    if declared_consumer_mod:
        synthetic_clean = {
            declared_consumer_mod: textwrap.dedent(f"""\
                # synthetic declared consumer — should produce no finding
                import json
                path = "{target_path}"
                data = json.load(open(path))
            """),
        }
        clean_findings = scan_findings(root, reg=reg, extra_files=synthetic_clean)
        clean_match = not any(
            f.artifact_id == target_art_id and f.module == declared_consumer_mod
            for f in clean_findings
        )
        status = "PASS" if clean_match else "FAIL"
        if not clean_match:
            all_passed = False
        print(f"  selftest [{status}] declared consumer -> clean (no finding for {declared_consumer_mod!r})")
    else:
        print("  selftest [SKIP] declared consumer -> clean (no engine/scripts consumer available)")

    print()
    if all_passed:
        print("selftest PASSED — all synthetic cases handled correctly")
        return 0
    else:
        print("selftest FAILED — one or more synthetic cases not caught")
        return 1


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=_REPO_ROOT,
        help="Repo root (default: parent of scripts/)",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="Scan and write ALL findings to the baseline file, then exit 0",
    )
    parser.add_argument(
        "--selftest",
        action="store_true",
        help="Run self-test with synthetic files; exit 0 on pass",
    )
    args = parser.parse_args()

    root = args.root.resolve()

    if args.selftest:
        print("Running synapse read-gate self-test...")
        return _run_selftest(root)

    # Load registry
    try:
        reg = load_registry(root)
    except FileNotFoundError as exc:
        print(f"[ERROR] {exc}")
        return 1

    # Scan
    findings = scan_findings(root, reg=reg)

    if args.write_baseline:
        _write_baseline(root, findings)
        return 0

    # Load baseline
    baseline = _load_baseline(root)

    n_artifacts = len(reg.get("artifacts") or {})
    print(
        f"synapse read-gate: scanned {n_artifacts} artifacts "
        f"({len(findings)} total finding(s))"
    )

    if not findings and baseline is None:
        print("read-gate CLEAN — no undeclared readers found (no baseline)")
        return 0

    n_warn, n_hard = _report_findings(findings, baseline, root)

    if n_hard > 0:
        print(
            f"\nread-gate HARD FAIL: {n_hard} Article-2 money-path undeclared reader(s). "
            f"Declare them as consumers in config/synapse.yml to pass."
        )
        return 1

    if n_warn > 0:
        print(
            f"\nread-gate WARN: {n_warn} undeclared reader(s) (warn tier — exit 0). "
            f"Declare them as consumers in config/synapse.yml to suppress."
        )
    else:
        print("read-gate CLEAN — all findings are baseline-suppressed")

    return 0


if __name__ == "__main__":
    sys.exit(main())
