def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def raw_universe_inventory(
    raw_dir: Path = RAW_DIR,
    *,
    include_content_hash: bool = False,
) -> tuple[list[Path], dict[str, Any]]:
    """Return sorted raw files and a deterministic inventory receipt.

    ``membership_sha256`` hashes relative filenames and is intentionally cheap enough for a
    nightly/CI drift sentinel. ``content_sha256`` additionally binds every source byte and is
    generated by full rebuilds only.
    """
    files = sorted(raw_dir.glob("*.parquet"), key=lambda path: path.name)
    names_payload = "".join(f"{path.name}\n" for path in files).encode("utf-8")
    inventory: dict[str, Any] = {
        "file_count": len(files),
        "membership_sha256": hashlib.sha256(names_payload).hexdigest(),
    }
    if include_content_hash:
        content_digest = hashlib.sha256()
        for path in files:
            content_digest.update(path.name.encode("utf-8"))
            content_digest.update(b"\0")
            content_digest.update(bytes.fromhex(_sha256_file(path)))
        inventory["content_sha256"] = content_digest.hexdigest()
    return files, inventory


def validate_completeness_manifest(
    manifest_path: Path = MANIFEST_PATH,
    raw_dir: Path = RAW_DIR,
) -> list[str]:
    """Return manifest/universe drift defects; an empty list means the sentinel passes."""
    if not manifest_path.exists():
        return [f"completeness manifest missing: {manifest_path}"]
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        return [f"completeness manifest unreadable: {exc}"]

    defects: list[str] = []
    if manifest.get("schema_version") != MANIFEST_SCHEMA_VERSION:
        defects.append(
            f"manifest schema mismatch: {manifest.get('schema_version')!r} "
            f"!= {MANIFEST_SCHEMA_VERSION!r}"
        )
    if manifest.get("complete") is not True:
        defects.append("manifest does not attest complete=true")

    _, current = raw_universe_inventory(raw_dir)
    recorded = manifest.get("raw_universe", {})
    for key in ("file_count", "membership_sha256"):
        if recorded.get(key) != current[key]:
            defects.append(
                f"raw universe {key} drift: manifest={recorded.get(key)!r} "
                f"current={current[key]!r}"
            )
    scan = manifest.get("scan", {})
    if scan.get("unreadable_count") != 0 or scan.get("unreadable_files"):
        defects.append("manifest reports unreadable raw files")
    if scan.get("files_scanned") != recorded.get("file_count"):
        defects.append("manifest scanned-file count does not cover the recorded universe")
    return defects


def _git_bytes(ref: str, relative_path: str) -> bytes:
    return subprocess.check_output(
        ["git", "show", f"{ref}:{relative_path}"],
        cwd=ROOT,
    )


def _git_blob(ref: str, relative_path: str) -> str:
    return subprocess.check_output(
        ["git", "rev-parse", f"{ref}:{relative_path}"],
        cwd=ROOT,
        text=True,
    ).strip()


def _baseline_universe_tickers() -> set[str]:
    paths = subprocess.check_output(
        [
            "git", "ls-tree", "-r", "--name-only", ORIGINAL_UNIVERSE_GIT_REF,
            "--", "data/china_stocks_raw",
        ],
        cwd=ROOT,
        text=True,
    ).splitlines()
    return {
        Path(path).stem
        for path in paths
        if path.endswith(".parquet")
    }


def _load_comparison_artifacts(
    comparison_ref: str | None,
) -> tuple[pd.DataFrame, set[str], dict[str, Any]]:
    """Load the exact pre-rebuild events/tape generation for a deterministic diff."""
    paths = {
        "events": "data/china_microstructure/limit_events.parquet",
        "tape": "data/china_microstructure/limit_tape.parquet",
    }
    if comparison_ref:
        events = pd.read_parquet(io.BytesIO(_git_bytes(comparison_ref, paths["events"])))
        tape = pd.read_parquet(io.BytesIO(_git_bytes(comparison_ref, paths["tape"])))
        source = {
            "kind": "git_ref",
            "ref": comparison_ref,
            "event_blob": _git_blob(comparison_ref, paths["events"]),
            "tape_blob": _git_blob(comparison_ref, paths["tape"]),
        }
    else:
        events = pd.read_parquet(EVENTS_PATH) if EVENTS_PATH.exists() else pd.DataFrame()
        tape = pd.read_parquet(TAPE_PATH) if TAPE_PATH.exists() else pd.DataFrame()
        source = {
            "kind": "preexisting_worktree_artifacts",
            "event_sha256": _sha256_file(EVENTS_PATH) if EVENTS_PATH.exists() else None,
            "tape_sha256": _sha256_file(TAPE_PATH) if TAPE_PATH.exists() else None,
        }
    tape_dates = (
        set(pd.to_datetime(tape["date"]).dt.strftime("%Y-%m-%d"))
        if not tape.empty and "date" in tape
        else set()
    )
    return events, tape_dates, source


def _event_slice_summary(frame: pd.DataFrame) -> dict[str, Any]:
    if frame.empty:
        return {"rows": 0, "tickers": 0, "by_ticker": {}, "by_event": {}, "by_year": {}}
    return {
        "rows": int(len(frame)),
        "tickers": int(frame["ticker"].nunique()),
        "by_ticker": {
            str(key): int(value)
            for key, value in frame["ticker"].value_counts().sort_index().items()
        },
        "by_event": {
            str(key): int(value)
            for key, value in frame["event"].value_counts().sort_index().items()
        },
        "by_year": {
            str(key): int(value)
            for key, value in frame["date"].dt.year.value_counts().sort_index().items()
        },
    }


def _raw_revision_evidence(tickers: set[str]) -> dict[str, Any]:
    """Count overlapping OHLCV bars changed since the original 1,587-file generation."""
    evidence: dict[str, Any] = {}
    for ticker in sorted(tickers):
        relpath = f"data/china_stocks_raw/{ticker}.parquet"
        old = pd.read_parquet(io.BytesIO(_git_bytes(ORIGINAL_UNIVERSE_GIT_REF, relpath)))
        current = pd.read_parquet(ROOT / relpath)
        old.index = pd.to_datetime(old.index)
        current.index = pd.to_datetime(current.index)
        common = old.index.intersection(current.index)
        columns = [
            col for col in ("open", "high", "low", "close", "volume")
            if col in old.columns and col in current.columns
        ]
        old_values = old.loc[common, columns]
        current_values = current.loc[common, columns]
        equal = old_values.eq(current_values) | (old_values.isna() & current_values.isna())
        changed = ~equal.all(axis=1)
        evidence[ticker] = {
            "baseline_blob": _git_blob(ORIGINAL_UNIVERSE_GIT_REF, relpath),
            "current_sha256": _sha256_file(ROOT / relpath),
            "overlapping_bars": len(common),
            "changed_overlapping_bars": int(changed.sum()),
            "first_changed_date": (
                pd.Timestamp(common[changed][0]).strftime("%Y-%m-%d") if changed.any() else None
            ),
            "last_changed_date": (
                pd.Timestamp(common[changed][-1]).strftime("%Y-%m-%d") if changed.any() else None
            ),
        }
    return evidence


def _event_reconciliation_receipt(
    prior_events: pd.DataFrame,
    rebuilt_events: pd.DataFrame,
    comparison_source: dict[str, Any],
    current_raw_files: list[Path],
) -> dict[str, Any]:
    """Explain every event-key delta against the selected prior generation exactly."""
    keys = ["date", "ticker", "event"]
    prior = prior_events.copy()
    rebuilt = rebuilt_events.copy()
    for frame in (prior, rebuilt):
        frame["date"] = pd.to_datetime(frame["date"])
    prior_duplicate_count = int(prior.duplicated(keys).sum())
    rebuilt_duplicate_count = int(rebuilt.duplicated(keys).sum())
    prior_keys = set(map(tuple, prior[keys].itertuples(index=False, name=None)))
    rebuilt_keys = set(map(tuple, rebuilt[keys].itertuples(index=False, name=None)))
    added_keys = rebuilt_keys - prior_keys
    removed_keys = prior_keys - rebuilt_keys
    added = rebuilt[rebuilt[keys].apply(tuple, axis=1).isin(added_keys)].copy()
    removed = prior[prior[keys].apply(tuple, axis=1).isin(removed_keys)].copy()

    original_tickers = _baseline_universe_tickers()
    current_tickers = {path.stem for path in current_raw_files}
    later_tickers = current_tickers - original_tickers
    broad_gap = rebuilt[
        rebuilt["ticker"].isin(later_tickers)
        & (rebuilt["date"] <= GAP_CENSUS_CUTOFF)
    ].copy()
    broad_gap_keys = set(map(tuple, broad_gap[keys].itertuples(index=False, name=None)))
    gap_overlap = len(prior_keys & broad_gap_keys)

    later_post_gap_added = added[
        added["ticker"].isin(later_tickers)
        & (added["date"] > GAP_CENSUS_CUTOFF)
    ]
    classifier_ticker = {"302132.SZ"}
    raw_delta_tickers = {"000990.SZ", "603663.SS", "300806.SZ", "002827.SZ", "301225.SZ"}
    classifier_added = added[added["ticker"].isin(classifier_ticker)]
    classifier_removed = removed[removed["ticker"].isin(classifier_ticker)]
    raw_delta_added = added[added["ticker"].isin(raw_delta_tickers)]
    raw_delta_removed = removed[removed["ticker"].isin(raw_delta_tickers)]

    # Main-board registration-era IPOs have no daily price limit for their first five sessions.
    # The earlier detector treated those rows as ordinary ±10% sessions.  Resolve the removed
    # keys from each ticker's immutable raw listing-relative index instead of hard-coding names.
    from engine.china_microstructure import MAIN_REGISTRATION_IPO_DATE

    registration_ipo_keys: set[tuple[Any, ...]] = set()
    for ticker in sorted(set(removed["ticker"].astype(str))):
        if _board_from_ticker(ticker) != "main":
            continue
        raw_path = RAW_DIR / f"{ticker}.parquet"
        if not raw_path.exists():
            continue
        raw_index = pd.to_datetime(pd.read_parquet(raw_path, columns=["close"]).index)
        raw_index = raw_index[~raw_index.isna()].sort_values().unique()
        if len(raw_index) == 0 or pd.Timestamp(raw_index[0]) < MAIN_REGISTRATION_IPO_DATE:
            continue
        no_limit_dates = {pd.Timestamp(ts) for ts in raw_index[:5]}
        ticker_rows = removed[
            (removed["ticker"] == ticker) & removed["date"].isin(no_limit_dates)
        ]
        registration_ipo_keys.update(
            map(tuple, ticker_rows[keys].itertuples(index=False, name=None))
        )
    registration_ipo_removed = removed[
        removed[keys].apply(tuple, axis=1).isin(registration_ipo_keys)
    ]

    explained_added_keys = set(map(tuple, pd.concat([
        broad_gap, later_post_gap_added, classifier_added, raw_delta_added,
    ])[keys].itertuples(index=False, name=None)))
    explained_removed_keys = set(map(tuple, pd.concat([
        classifier_removed, raw_delta_removed, registration_ipo_removed,
    ])[keys].itertuples(index=False, name=None)))
    unexplained_added = len(added_keys - explained_added_keys)
    unexplained_removed = len(removed_keys - explained_removed_keys)

    arithmetic_components = {
        "broad_gap_overlap_already_in_prior": -gap_overlap,
        "later_file_events_after_2026_06_30": len(later_post_gap_added),
        "current_raw_refresh_added": len(raw_delta_added),
        "classifier_302_chinext_added": len(classifier_added),
        "stale_prior_rows_removed_after_raw_refresh": -len(raw_delta_removed),
        "old_main_width_rows_removed_by_302_chinext_classifier": -len(classifier_removed),
        "registration_era_main_ipo_no_limit_rows_removed": -len(registration_ipo_removed),
        "unexplained_added": unexplained_added,
        "unexplained_removed": -unexplained_removed,
    }
    naive_rows = len(prior) + len(broad_gap)
    correction = sum(arithmetic_components.values())
    if naive_rows + correction != len(rebuilt):
        raise RuntimeError(
            "event reconciliation does not close: "
            f"{naive_rows} + {correction} != {len(rebuilt)}"
        )

    shared = prior.merge(rebuilt, on=keys, suffixes=("_prior", "_rebuilt"))
    shared_302 = shared[shared["ticker"] == "302132.SZ"]
    shared_board_relabels = int(
        (shared_302["board_prior"] != shared_302["board_rebuilt"]).sum()
    )
    event_bearing_added = set(rebuilt.loc[rebuilt["ticker"].isin(later_tickers), "ticker"])
    prior_added = set(prior.loc[prior["ticker"].isin(later_tickers), "ticker"])

    return {
        "comparison_source": comparison_source,
        "event_key": keys,
        "prior_rows": len(prior),
        "rebuilt_rows": len(rebuilt),
        "prior_duplicate_event_keys": prior_duplicate_count,
        "rebuilt_duplicate_event_keys": rebuilt_duplicate_count,
        "added_event_keys": len(added_keys),
        "removed_event_keys": len(removed_keys),
        "net_event_keys": len(added_keys) - len(removed_keys),
        "broad_gap_census": {
            "cutoff_inclusive": GAP_CENSUS_CUTOFF.strftime("%Y-%m-%d"),
            "original_raw_files": len(original_tickers),
            "current_raw_files": len(current_tickers),
            "later_added_files": len(later_tickers),
            "rows": len(broad_gap),
            "tickers": int(broad_gap["ticker"].nunique()),
            "rows_already_present_in_prior": gap_overlap,
            "event_bearing_later_tickers_absent_from_prior": len(
                event_bearing_added - prior_added
            ),
            "detail": _event_slice_summary(broad_gap),
        },
        "naive_prior_plus_broad_gap_rows": naive_rows,
        "rebuilt_minus_naive_rows": len(rebuilt) - naive_rows,
        "arithmetic_components": arithmetic_components,
        "added_detail": _event_slice_summary(added),
        "removed_detail": _event_slice_summary(removed),
        "reason_detail": {
            "later_file_post_gap_added": _event_slice_summary(later_post_gap_added),
            "current_raw_refresh_added": _event_slice_summary(raw_delta_added),
            "current_raw_refresh_removed": _event_slice_summary(raw_delta_removed),
            "classifier_302_chinext_added": _event_slice_summary(classifier_added),
            "classifier_302_chinext_removed": _event_slice_summary(classifier_removed),
            "classifier_302_shared_keys_relabelled_main_to_chinext": shared_board_relabels,
            "registration_era_main_ipo_no_limit_removed": _event_slice_summary(
                registration_ipo_removed
            ),
        },
        "raw_revision_evidence_vs_original_generation": _raw_revision_evidence(
            raw_delta_tickers
        ),
        "conclusion": (
            "Reconciliation closes exactly with no duplicate keys or residual delta: "
            f"{len(added_keys):,} event keys were added, {len(removed_keys):,} removed, "
            f"including {len(registration_ipo_removed):,} false registration-era main IPO "
            "no-limit rows removed."
        ),
    }


